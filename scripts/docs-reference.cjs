'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const rawBase = 'https://raw.githubusercontent.com/DeepMyst/Mysti/main/';
const json = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const code = value => {
  const text = String(value);
  const fence = '`'.repeat(Math.max(0, ...[...text.matchAll(/`+/g)].map(match => match[0].length)) + 1);
  const content = text.startsWith('`') || text.endsWith('`') ? ` ${text} ` : text;
  return fence + content + fence;
};
// GFM table escaping preserves the literal pipe inside a code span. An HTML
// entity inside backticks would become copyable entity text instead of a pipe.
const cell = value => String(value).replaceAll('|', '\\|').replaceAll('\n', '<br>');
const anchor = value => value.toLowerCase().replace(/[^\p{L}\p{N}_ -]/gu, '').replaceAll(' ', '-');

function buildReferences(pkg, labels, catalog) {
  function localize(value) {
    if (Array.isArray(value)) { return value.map(localize); }
    if (value && typeof value === 'object') {
      return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localize(item)]));
    }
    if (typeof value === 'string' && /^%[^%]+%$/.test(value)) {
      const key = value.slice(1, -1);
      if (!Object.hasOwn(labels, key)) { throw new Error(`Missing English localization: ${key}`); }
      return labels[key];
    }
    return value;
  }
  const configurations = Array.isArray(pkg.contributes.configuration)
    ? pkg.contributes.configuration : [pkg.contributes.configuration];
  const settings = localize(Object.assign({}, ...configurations.map(item => item.properties)));
  const commands = localize(pkg.contributes.commands).map(command => ({
    ...command,
    keybindings: (pkg.contributes.keybindings || []).filter(item => item.command === command.command),
    commandPalette: (pkg.contributes.menus?.commandPalette || []).filter(item => item.command === command.command),
  }));
  const sourceSha256 = crypto.createHash('sha256').update(JSON.stringify({ version: pkg.version, settings, commands })).digest('hex');
  const metadata = { schemaVersion: 1, productVersion: pkg.version,
    sources: ['package.json', 'package.nls.json'], sourceSha256 };
  const generated = '<!-- Generated by npm run docs:generate. Do not edit by hand. -->';
  const settingLink = text => text.replace(/`#(mysti\.[^#`]+)#`/g, (_, id) => `[${code(id)}](#${anchor(id)})`);
  const groups = new Map();
  for (const [key, spec] of Object.entries(settings)) {
    const group = key.split('.').length > 2 ? key.split('.')[1] : 'general-and-providers';
    if (!groups.has(group)) { groups.set(group, []); }
    groups.get(group).push([key, spec]);
  }
  let settingsMd = `${generated}\n# Settings reference\n\n` +
    `Declared configuration for Mysti **${pkg.version}**, generated from the manifest and English labels. ` +
    `There are **${Object.keys(settings).length} settings**.\n\n` +
    `Use VS Code Settings and search the exact key, or edit the appropriate settings JSON. ` +
    `Defaults here are declarations, not your effective configuration: user/workspace overrides, ` +
    `provider capabilities and authority clamps still apply. An empty model override uses provider/account selection.\n\n` +
    `Descriptions mirror the manifest; [provider setup](PROVIDERS.md) and [approval contracts](NATIVE_APPROVAL.md) ` +
    `explain current runtime limits. For credentials and telemetry, read [privacy](PRIVACY.md) first.\n\n` +
    `[Documentation home](README.md) · [Command reference](COMMANDS.md) · [Machine-readable settings](reference/settings.json)\n\n## Find a group\n\n`;
  for (const group of groups.keys()) { settingsMd += `- [${group}](#${anchor(group)})\n`; }
  for (const [group, values] of groups) {
    settingsMd += `\n## ${group}\n`;
    for (const [key, spec] of values) {
      settingsMd += `\n### ${code(key)}\n\n` +
        `${settingLink(spec.markdownDescription || spec.description || 'No description declared.')}\n\n` +
        `| Type | Declared default | Declared scope |\n| --- | --- | --- |\n` +
        `| ${cell(code(Array.isArray(spec.type) ? spec.type.join(' / ') : spec.type || 'unspecified'))} | ` +
        `${Object.hasOwn(spec, 'default') ? cell(code(JSON.stringify(spec.default))) : 'Not declared'} | ` +
        `${spec.scope ? code(spec.scope) : 'Not declared'} |\n`;
      if (spec.enum) { settingsMd += `\nAllowed values: ${spec.enum.map(value => code(JSON.stringify(value))).join(', ')}.\n`; }
      if (spec.items?.enum) { settingsMd += `\nAllowed array entries: ${spec.items.enum.map(value => code(JSON.stringify(value))).join(', ')}.\n`; }
      if (spec.minimum !== undefined || spec.maximum !== undefined) {
        settingsMd += `\nDeclared bounds: ${spec.minimum !== undefined ? `minimum ${spec.minimum}` : 'no minimum'}; ` +
          `${spec.maximum !== undefined ? `maximum ${spec.maximum}` : 'no maximum'}.\n`;
      }
      const deprecated = spec.markdownDeprecationMessage || spec.deprecationMessage;
      if (deprecated) { settingsMd += `\n**Deprecated:** ${settingLink(deprecated)}\n`; }
    }
  }
  let commandsMd = `${generated}\n# Command reference\n\n` +
    `The **${commands.length} contributed commands** for Mysti **${pkg.version}**, generated from ` +
    `the manifest and English labels. Open VS Code's Command Palette and search the displayed title.\n\n` +
    `Visibility and enablement conditions are declarations; workspace trust, runtime registration ` +
    `and the active editor still affect availability. Some commands require an editor selection, ` +
    `internal arguments or a development context. A command's presence does not establish native feature acceptance.\n\n` +
    `These are VS Code commands. Chat slash commands and provider-native commands are different surfaces; ` +
    `see [the feature guide](FEATURES.md#slash-commands) and [agent assignments](MENTIONS.md).\n\n` +
    `[Documentation home](README.md) · [Settings](SETTINGS.md) · [Machine-readable commands](reference/commands.json)\n\n` +
    `| Displayed title | Command ID |\n| --- | --- |\n`;
  for (const command of commands) {
    commandsMd += `| [${cell((command.category ? command.category + ': ' : '') + command.title)}](#${anchor(command.command)}) | ${code(command.command)} |\n`;
  }
  for (const command of commands) {
    commandsMd += `\n## ${code(command.command)}\n\n**${command.category ? command.category + ': ' : ''}${command.title}**\n\n`;
    commandsMd += `Command Palette condition: ${command.commandPalette.length
      ? command.commandPalette.map(item => code(item.when || 'always')).join('; ')
      : 'no extra condition declared'}.\n`;
    if (command.enablement) { commandsMd += `\nEnablement: ${code(command.enablement)}.\n`; }
    for (const binding of command.keybindings) {
      commandsMd += `\nShortcut: ${code(binding.key)}${binding.mac ? `; macOS ${code(binding.mac)}` : ''}` +
        `${binding.linux ? `; Linux ${code(binding.linux)}` : ''}${binding.win ? `; Windows ${code(binding.win)}` : ''}` +
        `${binding.when ? `; when ${code(binding.when)}` : ''}.\n`;
    }
  }
  let llms = '# Mysti\n\n> A beta VS Code extension for working with coding agents, shared context, visual artifacts and explicit multi-agent workflows.\n\n' +
    `This index describes the ${pkg.version} source line. Fetch the smallest relevant guide; ` +
    'settings and command references are generated from the manifest. Account access, native approvals and ' +
    'production acceptance vary by provider. Recordings use labelled sample data. ' +
    'Current source and the production-readiness report take precedence over historical plans. ' +
    'In a checkout, use these repository-relative paths for your revision; the URLs track published main.\n\n' +
    '## Start here\n\n' +
    `- [Documentation home](${rawBase}docs/README.md): Routes by task and audience.\n` +
    `- [Repository agent guidance](${rawBase}AGENTS.md): Working conventions and validation commands.\n` +
    `- [Structured navigation](${rawBase}docs/navigation.json): Topics, audiences and document status.\n\n` +
    '## Guides and references\n\n';
  for (const doc of catalog.documents.filter(doc => doc.status === 'current')) {
    llms += `- [${doc.title}](${rawBase}${doc.path}): ${doc.summary}\n`;
  }
  llms += '\n## Optional\n\n';
  for (const doc of catalog.documents.filter(doc => doc.status !== 'current')) {
    llms += `- [${doc.title}](${rawBase}${doc.path}): ${doc.summary}\n`;
  }
  return new Map([
    ['docs/SETTINGS.md', settingsMd], ['docs/COMMANDS.md', commandsMd],
    ['docs/reference/settings.json', JSON.stringify({ ...metadata, settings }, null, 2) + '\n'],
    ['docs/reference/commands.json', JSON.stringify({ ...metadata, commands }, null, 2) + '\n'],
    ['llms.txt', llms],
  ]);
}

function generate(write = false) {
  const outputs = buildReferences(json('package.json'), json('package.nls.json'), json('docs/navigation.json'));
  const stale = [];
  for (const [file, content] of outputs) {
    const target = path.join(root, file);
    if (write) { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
    else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) { stale.push(file); }
  }
  if (stale.length) { throw new Error(`Generated documentation is stale: ${stale.join(', ')}. Run npm run docs:generate and review the diff.`); }
  return outputs.size;
}

if (require.main === module) {
  try {
    if (process.argv.slice(2).some(arg => !['--write', '--check'].includes(arg))) { throw new Error('Usage: node scripts/docs-reference.cjs [--write|--check]'); }
    const write = process.argv.includes('--write');
    console.log(`${write ? 'Generated' : 'Verified'} ${generate(write)} documentation files.`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { buildReferences, generate, anchor };
